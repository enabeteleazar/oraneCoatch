/**
 * Accès à la base Postgres.
 * - Production : Neon (variable DATABASE_URL), via le pilote HTTP serverless.
 * - Développement sans DATABASE_URL : base locale embarquée (PGlite) dans `.data/pglite`.
 * Les tables sont créées automatiquement au premier appel (voir aussi db/schema.sql).
 */

export type Ligne = Record<string, unknown>;
type Executeur = (texte: string, params: unknown[]) => Promise<Ligne[]>;

export type ModeBase = "neon" | "local" | "aucune";

export function modeBase(): ModeBase {
  if (process.env.DATABASE_URL) return "neon";
  if (!process.env.VERCEL && process.env.NODE_ENV !== "production") return "local";
  return "aucune";
}

const SCHEMA = [
  `CREATE TABLE IF NOT EXISTS booking_slots (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    starts_at     timestamptz NOT NULL,
    ends_at       timestamptz NOT NULL,
    slot_type     text NOT NULL CHECK (slot_type IN ('decouverte', 'seance')),
    enabled       boolean NOT NULL DEFAULT true,
    claimed_until timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT booking_slots_ordre CHECK (ends_at > starts_at),
    CONSTRAINT booking_slots_pas_de_chevauchement EXCLUDE USING gist (tstzrange(starts_at, ends_at) WITH &&)
  )`,
  `ALTER TABLE booking_slots ADD COLUMN IF NOT EXISTS enabled boolean NOT NULL DEFAULT true`,
  `CREATE INDEX IF NOT EXISTS booking_slots_starts_at_idx ON booking_slots (starts_at)`,
  `CREATE TABLE IF NOT EXISTS site_settings (
    key        text PRIMARY KEY,
    value      jsonb NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
  )`,
  `CREATE TABLE IF NOT EXISTS rate_limits (
    key        text PRIMARY KEY,
    count      integer NOT NULL,
    expires_at timestamptz NOT NULL
  )`,
];

function migrerAnciensCreneaux(exec: Executeur): Promise<Ligne[]> {
  const fuseau = (process.env.BOOKING_TIME_ZONE || "Europe/Paris").replaceAll("'", "''");

  return exec(
    `DO $migration$
    DECLARE
      fuseau text := '${fuseau}';
      ancien record;
      debut timestamptz;
      fin timestamptz;
      statut text;
    BEGIN
      PERFORM pg_advisory_xact_lock(hashtext('orane:booking-slots-migration'));

      IF to_regclass('public.booking_slots') IS NOT NULL
        AND EXISTS (
          SELECT 1 FROM information_schema.columns
          WHERE table_schema = 'public' AND table_name = 'booking_slots' AND column_name = 'slot_date'
        )
        AND NOT EXISTS (
          SELECT 1 FROM information_schema.columns
          WHERE table_schema = 'public' AND table_name = 'booking_slots' AND column_name = 'starts_at'
        )
      THEN
        IF to_regclass('public.booking_slots_legacy') IS NOT NULL THEN
          RAISE EXCEPTION 'Les tables booking_slots et booking_slots_legacy existent toutes deux; migration automatique interrompue.';
        END IF;
        ALTER TABLE public.booking_slots RENAME TO booking_slots_legacy;
      END IF;

      CREATE TABLE IF NOT EXISTS public.booking_slots (
        id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
        starts_at     timestamptz NOT NULL,
        ends_at       timestamptz NOT NULL,
        slot_type     text NOT NULL CHECK (slot_type IN ('decouverte', 'seance')),
        enabled       boolean NOT NULL DEFAULT true,
        claimed_until timestamptz,
        created_at    timestamptz NOT NULL DEFAULT now(),
        CONSTRAINT booking_slots_ordre CHECK (ends_at > starts_at),
        CONSTRAINT booking_slots_pas_de_chevauchement EXCLUDE USING gist (tstzrange(starts_at, ends_at) WITH &&)
      );
      ALTER TABLE public.booking_slots ADD COLUMN IF NOT EXISTS enabled boolean NOT NULL DEFAULT true;
      CREATE TABLE IF NOT EXISTS public.booking_slots_legacy (
        id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slot_date  date NOT NULL,
        start_time time without time zone NOT NULL,
        end_time   time without time zone NOT NULL,
        enabled    boolean NOT NULL DEFAULT true,
        created_at timestamp without time zone NOT NULL DEFAULT now()
      );
      CREATE TABLE IF NOT EXISTS public.booking_slots_legacy_migrations (
        legacy_id integer PRIMARY KEY,
        status text NOT NULL,
        migrated_at timestamptz NOT NULL DEFAULT now()
      );
      CREATE TABLE IF NOT EXISTS public.schema_migrations (
        name text PRIMARY KEY,
        completed_at timestamptz NOT NULL DEFAULT now()
      );

      IF to_regclass('public.booking_slots_legacy') IS NOT NULL
        AND NOT EXISTS (
          SELECT 1 FROM public.schema_migrations WHERE name = 'legacy-booking-slots-v1'
        )
      THEN
        FOR ancien IN
          SELECT id, slot_date, start_time, end_time, enabled
          FROM public.booking_slots_legacy
          ORDER BY slot_date, start_time, id
        LOOP
          IF EXISTS (
            SELECT 1 FROM public.booking_slots_legacy_migrations WHERE legacy_id = ancien.id
          ) THEN
            CONTINUE;
          END IF;

          IF ancien.end_time <= ancien.start_time THEN
            statut := 'invalid';
          ELSE
            debut := (ancien.slot_date + ancien.start_time) AT TIME ZONE fuseau;
            fin := (ancien.slot_date + ancien.end_time) AT TIME ZONE fuseau;
            IF EXISTS (
              SELECT 1 FROM public.booking_slots
              WHERE tstzrange(starts_at, ends_at) && tstzrange(debut, fin)
            ) THEN
              statut := 'overlap';
            ELSE
              INSERT INTO public.booking_slots (starts_at, ends_at, slot_type, enabled)
              VALUES (debut, fin, 'seance', ancien.enabled);
              statut := 'migrated';
            END IF;
          END IF;

          INSERT INTO public.booking_slots_legacy_migrations (legacy_id, status)
          VALUES (ancien.id, statut);
        END LOOP;

        INSERT INTO public.schema_migrations (name)
        VALUES ('legacy-booking-slots-v1')
        ON CONFLICT (name) DO NOTHING;
      END IF;
    END
    $migration$;`,
    [],
  );
}

let executeur: Promise<Executeur> | null = null;
let schemaPret: Promise<void> | null = null;

async function creerExecuteur(): Promise<Executeur> {
  const url = process.env.DATABASE_URL;
  if (url) {
    const { neon } = await import("@neondatabase/serverless");
    const sql = neon(url);
    return async (texte, params) => (await sql.query(texte, params)) as Ligne[];
  }
  if (modeBase() === "local") {
    const nomPaquet = "@electric-sql/pglite"; // nom en variable : jamais embarqué dans les fonctions Vercel
    const { PGlite } = await import(/* @vite-ignore */ nomPaquet).catch(() => {
      throw new Error(
        "DATABASE_URL n'est pas défini et la base locale n'est pas installée : renseignez DATABASE_URL dans .env.local (connexion Neon) ou lancez « pnpm add -D @electric-sql/pglite ».",
      );
    });
    const dossier = process.env.PGLITE_DIR ?? ".data/pglite";
    const { mkdir } = await import("node:fs/promises");
    const { dirname } = await import("node:path");
    await mkdir(dirname(dossier), { recursive: true });
    const base = new PGlite(dossier);
    await base.waitReady;
    return async (texte, params) => (await base.query(texte, params)).rows as Ligne[];
  }
  throw new Error("DATABASE_URL n'est pas défini");
}

async function creerSchema(exec: Executeur): Promise<void> {
  try {
    await migrerAnciensCreneaux(exec);
  } catch (erreur) {
    await migrerAnciensCreneaux(exec).catch(() => {
      throw erreur;
    });
  }

  for (const instruction of SCHEMA) {
    try {
      await exec(instruction, []);
    } catch (erreur) {
      // Deux démarrages simultanés peuvent se disputer la création : on réessaie une fois.
      await exec(instruction, []).catch(() => {
        throw erreur;
      });
    }
  }
}

/** Exécute une requête paramétrée ($1, $2…) et renvoie les lignes. */
export async function requete(texte: string, params: unknown[] = []): Promise<Ligne[]> {
  executeur ??= creerExecuteur();
  const exec = await executeur.catch((erreur) => {
    executeur = null;
    throw erreur;
  });
  schemaPret ??= creerSchema(exec).catch((erreur) => {
    schemaPret = null;
    throw erreur;
  });
  await schemaPret;
  return exec(texte, params);
}

export const enIso = (v: unknown): string => new Date(v as string | number | Date).toISOString();
